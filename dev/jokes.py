from playwright.sync_api import sync_playwright
def banner(pg): return pg.inner_text('#intro-banner .sr')
with sync_playwright() as p:
    b = p.chromium.launch(); pg = b.new_page(viewport={'width': 390, 'height': 844})
    errs = []; pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto('file:///home/claude/skat/dev/test.html'); pg.evaluate("localStorage.clear()"); pg.reload(); pg.wait_for_timeout(300)
    pg.click('#intro-start'); pg.wait_for_timeout(300); pg.click('#intro-skip'); pg.wait_for_timeout(2500)
    h0 = pg.evaluate("document.getElementById('intro-banner').offsetHeight")
    pg.type('#name-0', 'Jan', delay=80); pg.keyboard.press('Enter'); pg.wait_for_timeout(300)
    print('1 Jan oben:', banner(pg))
    pg.type('#name-1', 'Charlotte', delay=60); pg.keyboard.press('Enter'); pg.wait_for_timeout(1500)
    print('2 Charlotte darunter (bleibt Jan):', banner(pg))
    pg.fill('#name-0', ''); pg.type('#name-0', 'Anna', delay=50); pg.keyboard.press('Tab'); pg.wait_for_timeout(1300)
    print('3 Jan weg, Anna:', banner(pg))
    pg.click('#name-1'); pg.keyboard.press('Tab'); pg.wait_for_timeout(300)
    print('4 Charlotte jetzt oberste, Feld verlassen:', banner(pg))
    pg.type('#name-2', 'Matti', delay=60); pg.wait_for_timeout(1400)
    print('5 Matti unter Charlotte:', banner(pg))
    pg.fill('#name-1', 'Ben'); pg.click('#name-2'); pg.keyboard.press('Tab'); pg.wait_for_timeout(300)
    print('6 Matti jetzt oberste:', banner(pg))
    for n in ['Naunin', 'Philip', 'Till', 'Matteo']:
        pg.fill('#name-2', 'X'); pg.wait_for_timeout(50); pg.fill('#name-2', ''); pg.type('#name-2', n, delay=40); pg.wait_for_timeout(1300)
        print('  ', n + ':', banner(pg))
    print('Banner-Höhe gleich:', h0 == pg.evaluate("document.getElementById('intro-banner').offsetHeight"))
    print('Fehler:', errs)
    b.close()
