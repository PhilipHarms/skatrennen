from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b = p.chromium.launch()
    pg = b.new_page(viewport={'width':390,'height':844})
    errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto('file:///home/claude/skat/dev/test.html')
    pg.evaluate("localStorage.clear()"); pg.reload(); pg.wait_for_timeout(300)
    for i in range(3): pg.click('#onb-next')
    pg.fill('#name-0','Anna'); pg.fill('#name-1','Ben'); pg.fill('#name-2','Carla')
    for i in range(4): pg.click('#onb-next'); pg.wait_for_timeout(100)
    pg.click('#btn-enter'); pg.wait_for_timeout(150)
    pg.click('#entry-body [data-k=mode]'); pg.wait_for_timeout(100)
    pg.click('#entry-body [data-k=player] >> nth=0'); pg.fill('#fp','30'); pg.click('#entry-ok'); pg.wait_for_timeout(300)
    print('setting after switch:', pg.evaluate('S.settings.manual'), '| button:', pg.inner_text('#btn-enter'))
    pg.reload(); pg.wait_for_timeout(600)
    pg.click('#btn-enter'); pg.wait_for_timeout(150)
    print('after reload manual sheet:', pg.is_visible('#fp'), '| button:', pg.inner_text('#btn-enter'))
    pg.click('#entry-body [data-k=mode]'); pg.wait_for_timeout(100); pg.keyboard.press('Escape')
    print('switched back:', pg.evaluate('S.settings.manual'))
    print(errs)
    b.close()
